#!/usr/bin/env python3
"""Manage the firmware signing key.

    python tools/keys.py generate      create secrets/mcuboot_signing_key.pem (never overwrites)
    python tools/keys.py public        (re)write firmware/keys/fw_signing_pub.pem from the private key
    python tools/keys.py fingerprint   print the SHA-256 of the public key, as MCUboot stores it

The private key is an ECDSA P-256 key generated by MCUboot's own imgtool. It is the one
secret that decides which firmware the boards will run, so it lives only in the ignored
secrets/ directory with owner-only permissions. Only the public half is committed.

Run from an nRF Connect SDK environment (ZEPHYR_BASE set), which provides imgtool and the
"cryptography" package.
"""

import argparse
import hashlib
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PRIVATE_KEY = REPO / "secrets" / "mcuboot_signing_key.pem"
PUBLIC_KEY = REPO / "firmware" / "keys" / "fw_signing_pub.pem"


def imgtool() -> Path:
    base = os.environ.get("ZEPHYR_BASE")
    if not base:
        sys.exit("ZEPHYR_BASE is not set: run this from an nRF Connect SDK terminal")
    path = Path(base).parent / "bootloader" / "mcuboot" / "scripts" / "imgtool.py"
    if not path.is_file():
        sys.exit(f"imgtool not found at {path}")
    return path


def load_public_der() -> bytes:
    from cryptography.hazmat.primitives import serialization

    if not PRIVATE_KEY.is_file():
        sys.exit(f"{PRIVATE_KEY} does not exist: run 'python tools/keys.py generate' "
                 "or obtain the team key from the key custodian")
    key = serialization.load_pem_private_key(PRIVATE_KEY.read_bytes(), password=None)
    return key.public_key().public_bytes(
        serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)


def write_public() -> None:
    from cryptography.hazmat.primitives import serialization

    der = load_public_der()
    pem = serialization.load_der_public_key(der).public_bytes(
        serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo)
    PUBLIC_KEY.parent.mkdir(parents=True, exist_ok=True)
    PUBLIC_KEY.write_bytes(pem)
    print(f"public key  {PUBLIC_KEY.relative_to(REPO)}")
    print(f"fingerprint {hashlib.sha256(der).hexdigest()}")


def generate() -> None:
    if PRIVATE_KEY.exists():
        sys.exit(f"{PRIVATE_KEY} already exists. Refusing to replace it: every board that "
                 "was flashed with the matching bootloader would reject all future updates.")
    PRIVATE_KEY.parent.mkdir(mode=0o700, exist_ok=True)
    old_umask = os.umask(0o077)
    try:
        subprocess.run([sys.executable, str(imgtool()), "keygen", "-t", "ecdsa-p256",
                        "-k", str(PRIVATE_KEY)], check=True)
    finally:
        os.umask(old_umask)
    os.chmod(PRIVATE_KEY, 0o600)
    print(f"private key {PRIVATE_KEY.relative_to(REPO)} (owner read/write only, ignored by git)")
    write_public()
    print("Back the private key up somewhere safe and share it only over a secure channel.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=["generate", "public", "fingerprint"])
    args = parser.parse_args()
    if args.command == "generate":
        generate()
    elif args.command == "public":
        write_public()
    else:
        print(hashlib.sha256(load_public_der()).hexdigest())


if __name__ == "__main__":
    main()
