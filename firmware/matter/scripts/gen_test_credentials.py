#!/usr/bin/env python3
"""Writes the board's Matter TEST device credentials into a C file in the build folder, taken from the Matter SDK
in the build's SDK (connectedhomeip, src/credentials/examples): the example DAC for vendor 0xFFF1 / product
0x8000 with its private key, its PAI, and the test certification declaration for vendor 0xFFF1.

These are the Matter SDK's published test credentials: any controller in test mode accepts them, and nothing in
production does. They are generated at build time so that no key is kept in this repository.

    python3 -I gen_test_credentials.py <connectedhomeip directory> <output .c file>
"""

import re
import sys


def arrays(path: str) -> dict:
    text = open(path, encoding="utf-8").read()
    found = {}
    for m in re.finditer(r"const uint8_t (\w+)\[\d*\]\s*=\s*\{(.*?)\};", text, re.S):
        found.setdefault(m.group(1), []).append(bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(2))))
    return found


def c_array(name: str, data: bytes) -> str:
    lines = [f"const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"const size_t {name}_len = sizeof({name});")
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    chip, out = sys.argv[1], sys.argv[2]
    ex = chip + "/src/credentials/examples/"
    dacs = arrays(ex + "ExampleDACs.cpp")
    pais = arrays(ex + "ExamplePAI.cpp")
    cds = arrays(ex + "DeviceAttestationCredsExample.cpp")
    dac = dacs["kDevelopmentDAC_Cert_FFF1_8000"][0]
    key = dacs["kDevelopmentDAC_PrivateKey_FFF1_8000"][0]
    pai = pais["kDevelopmentPAI_Cert_FFF1"][0]
    # The last of the three is the vendor 0xFFF1 declaration (the #else branch).
    cd = cds["kCdForAllExamples"][-1]
    if len(key) != 32 or dac[0] != 0x30 or pai[0] != 0x30 or cd[0] != 0x30:
        sys.exit("gen_test_credentials: unexpected credentials in the Matter SDK")
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Generated by firmware/matter/scripts/gen_test_credentials.py: Matter SDK TEST credentials. */\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
        for name, data in (("mt_test_dac", dac), ("mt_test_dac_key", key), ("mt_test_pai", pai), ("mt_test_cd", cd)):
            f.write(c_array(name, data) + "\n\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
